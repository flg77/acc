"""The memory lifecycle as PROV-O — a projection of the refinement ledger (RDF-03).

The ledger (``acc/refinements.py``) is the source of truth; this is a view of
it that can be thrown away and rebuilt from the rows at any time.  One ledger
row is one ``acc:Refinement`` activity; what it produced or touched becomes an
entity:

=============  ==============================================================
row kind       projection
=============  ==============================================================
note           ``acc:Note`` ← ``prov:wasDerivedFrom`` its episodes;
               ``acc:sourceRequester`` the people it rests on
propose        ``acc:Proposal`` generated by the row, which ``prov:used`` the note
publish /      ``acc:PublishedNote`` (one per role + destination) derived from
hub_promote    the note; one ``prov:qualifiedAssociation`` per approver with
               ``acc:approverTier``; ``acc:written``
adopt          ``acc:PublishedNote`` in the adopting role, derived from the
               producer's note and its episodes
forget         ``acc:Erasure``; deleted notes ``prov:wasInvalidatedBy`` it,
               rebuilt / demoted ones ``acc:revised``.  The erased person is
               **not** linked (see below)
rollback       the reverted note or copy ``prov:wasInvalidatedBy`` it
outcome        the task ``prov:used`` the lesson's note; ``acc:verdict``
=============  ==============================================================

``role_patch`` and ``rule`` rows change a role, not memory, and are skipped.

**The erasure keeps no person.**  The ``forget`` row names who was erased; the
projection does not carry that into the graph, so the graph never becomes the
index that re-identifies an erased person.  Whether the *ledger row itself*
should keep the id is an open operator decision (RDF-03).

Pure: rows in, :class:`~acc.lib.rdf.graph.Graph` out, plus two traversals --
:func:`lineage` (where a note came from and went) and :func:`contributions`
(everything resting on one person, across collectives: the erasure plan).
"""

from __future__ import annotations

from collections import deque
from dataclasses import dataclass, field
from typing import Any, Callable, Iterable

from acc.lib.rdf.graph import Graph
from acc.lib.rdf.iri import Persons, collective_iri, local_iri, role_iri
from acc.lib.rdf.terms import ACC, PROV, RDF, BNode, datetime_lit, lit
from acc.lib.rdf.vocab import ceiling_iri

#: Kinds the projection reads.  Anything else in the ledger is skipped.
MEMORY_KINDS = ("note", "propose", "publish", "hub_promote", "adopt", "forget", "rollback", "outcome")


def note_iri(collective_id: str, note_id: str) -> str:
    return local_iri(collective_id, "note", note_id)


def copy_iri(collective_id: str, role_label: str, destination: str, note_id: str) -> str:
    """A note's copy in one destination for one role (shared keys are per role)."""
    return local_iri(collective_id, "published", f"{role_label}/{destination}/{note_id}")


def _text(value: Any) -> str:
    return str(value if value is not None else "").strip()


@dataclass
class Projection:
    """The graph, and how its people were named (to look one up again)."""

    graph: Graph
    persons: Persons
    person_of: Callable[[str], str]
    rows_read: int = 0
    rows_skipped: int = 0

    def person(self, subject: str) -> str | BNode:
        return self.persons.node(self.person_of(subject))


def project(
    rows: Iterable[dict[str, Any]],
    *,
    persons: Persons | None = None,
    person_of: Callable[[str], str] | None = None,
) -> Projection:
    """Build the provenance graph from ledger rows (any order).

    *person_of* maps a requester string to its person (the runtime passes
    :func:`acc.attribution.person_of`, which folds ``slack:U1@C1`` and
    ``slack:U1@C2`` into one person); the default keeps strings as they are.
    """
    proj = Projection(graph=Graph(), persons=persons or Persons(),
                      person_of=person_of or (lambda s: str(s).strip()))
    for row in rows:
        if not isinstance(row, dict) or row.get("kind") not in MEMORY_KINDS:
            proj.rows_skipped += 1
            continue
        try:
            _ROW[row["kind"]](proj, row)
            proj.rows_read += 1
        except (ValueError, TypeError, KeyError):
            proj.rows_skipped += 1
    return proj


# ---------------------------------------------------------------------------
# one function per row kind
# ---------------------------------------------------------------------------
def _activity(proj: Projection, row: dict[str, Any], cls: str = ACC.Refinement) -> str:
    g = proj.graph
    cid = _text(row.get("collective_id")) or "local"
    act = local_iri(cid, "refinement", _text(row.get("refinement_id")))
    g.add(act, RDF.type, cls)
    g.add(act, ACC.refinementKind, lit(_text(row.get("kind"))))
    g.add(act, ACC.collective, collective_iri(cid))
    if row.get("ts"):
        g.add(act, PROV.endedAtTime, datetime_lit(float(row["ts"])))
    agent = _text(row.get("agent_id"))
    if agent:
        g.add(act, PROV.wasAssociatedWith, _agent(proj, cid, agent))
    return act


def _agent(proj: Projection, cid: str, agent_id: str) -> str:
    node = local_iri(cid, "agent", agent_id)
    proj.graph.add(node, RDF.type, ACC.Agent)
    return node


def _people(proj: Projection, node: str, subjects: Iterable[Any]) -> None:
    g = proj.graph
    for subject in subjects or []:
        if _text(subject):
            person = proj.person(_text(subject))
            g.add(person, RDF.type, PROV.Person)
            g.add(node, ACC.sourceRequester, person)


def _episodes(proj: Projection, cid: str, node: str, ids: Iterable[Any]) -> None:
    for episode in ids or []:
        if _text(episode):
            ep = local_iri(cid, "episode", _text(episode))
            proj.graph.add(ep, RDF.type, ACC.Episode)
            proj.graph.add(node, PROV.wasDerivedFrom, ep)


def _held(proj: Projection, node: str, cid: str, role: str, row: dict[str, Any]) -> None:
    """Where an entity lives and how far it may be read."""
    g = proj.graph
    g.add(node, ACC.collective, collective_iri(cid))
    g.add(node, ACC.ceiling, ceiling_iri(_text(row.get("ceiling"))))
    if role:
        g.add(node, ACC.role, role_iri(role))
    if _text(row.get("scope")):
        g.add(node, ACC.scope, lit(_text(row["scope"])))


def _note(proj: Projection, row: dict[str, Any]) -> None:
    g = proj.graph
    cid = _text(row.get("collective_id")) or "local"
    note_id = _text((row.get("target") or {}).get("id"))
    if not note_id:
        raise ValueError("note row without a note id")
    act = _activity(proj, row)
    node = note_iri(cid, note_id)
    g.add(node, RDF.type, ACC.Note)
    g.add(node, PROV.wasGeneratedBy, act)
    if row.get("ts"):
        g.add(node, PROV.generatedAtTime, datetime_lit(float(row["ts"])))
    if _text(row.get("agent_id")):
        g.add(node, PROV.wasAttributedTo, _agent(proj, cid, _text(row["agent_id"])))
    _held(proj, node, cid, _text(row.get("role_label")), row)
    ev = row.get("evidence") or {}
    _episodes(proj, cid, node, ev.get("source_episode_ids"))
    _people(proj, node, ev.get("source_requesters"))
    if _text(ev.get("dissent")):
        g.add(node, ACC.dissent, lit(_text(ev["dissent"])))


def _propose(proj: Projection, row: dict[str, Any]) -> None:
    g = proj.graph
    cid = _text(row.get("collective_id")) or "local"
    ev, tgt = row.get("evidence") or {}, row.get("target") or {}
    proposal_id = _text(ev.get("proposal_id"))
    if not proposal_id:
        raise ValueError("propose row without a proposal id")
    act = _activity(proj, row)
    node = local_iri(cid, "proposal", proposal_id)
    g.add(node, RDF.type, ACC.Proposal)
    g.add(node, PROV.wasGeneratedBy, act)
    g.add(node, ACC.destination, lit(_text(tgt.get("destination"))))
    _held(proj, node, cid, _text(row.get("role_label")), row)
    source = _text(tgt.get("source_collective")) or cid
    if _text(tgt.get("id")):
        g.add(act, PROV.used, note_iri(source, _text(tgt["id"])))
    by = _text(ev.get("proposed_by"))
    # An agent id has no source prefix; a person's attribution does
    # (``k8s:user/alice``, ``system:flg``).  The proposer is one or the other.
    if ":" in by:
        person = proj.person(by)
        g.add(person, RDF.type, PROV.Person)
        g.add(act, PROV.wasAssociatedWith, person)
    _episodes(proj, source, node, ev.get("source_ids"))


def _publish(proj: Projection, row: dict[str, Any]) -> None:
    g = proj.graph
    cid = _text(row.get("collective_id")) or "local"
    ev, tgt = row.get("evidence") or {}, row.get("target") or {}
    note_id = _text(tgt.get("id"))
    destination = _text(tgt.get("destination"))
    if not note_id or not destination:
        raise ValueError("publish row without a note or destination")
    role = _text(row.get("role_label"))
    dest_cid = _text(tgt.get("destination_collective")) or cid
    source = _text(tgt.get("source_collective")) or cid
    act = _activity(proj, row)
    note = note_iri(source, note_id)
    node = copy_iri(dest_cid, role, destination, note_id)
    g.add(node, RDF.type, ACC.PublishedNote)
    g.add(node, PROV.wasDerivedFrom, note)
    g.add(node, PROV.wasGeneratedBy, act)
    g.add(node, ACC.destination, lit(destination))
    _held(proj, node, dest_cid, role, {**row, "scope": ""})
    g.add(act, PROV.used, note)
    if _text(ev.get("proposal_id")):
        g.add(act, PROV.used, local_iri(cid, "proposal", _text(ev["proposal_id"])))
    if "written" in tgt:
        g.add(act, ACC.written, lit(bool(tgt["written"])))
    approvals = [a for a in (ev.get("approvals") or []) if isinstance(a, dict) and a.get("approver_id")]
    if not approvals and _text(row.get("approver")):
        # A row from before RDF-03 2a: one approver, tier unknown.
        approvals = [{"approver_id": row["approver"], "approver_tier": ""}]
    for i, approval in enumerate(approvals):
        assoc = BNode(f"approval-{_text(row.get('refinement_id'))[:12]}-{i}")
        person = proj.person(_text(approval["approver_id"]))
        g.add(person, RDF.type, PROV.Person)
        g.add(act, PROV.qualifiedAssociation, assoc)
        g.add(assoc, RDF.type, PROV.Association)
        g.add(assoc, PROV.agent, person)
        if _text(approval.get("approver_tier")):
            g.add(assoc, ACC.approverTier, lit(_text(approval["approver_tier"])))
    _episodes(proj, source, node, ev.get("source_ids"))
    _people(proj, node, ev.get("source_requesters"))


def _adopt(proj: Projection, row: dict[str, Any]) -> None:
    g = proj.graph
    cid = _text(row.get("collective_id")) or "local"
    ev, tgt = row.get("evidence") or {}, row.get("target") or {}
    note_id = _text(tgt.get("id"))
    if not note_id:
        raise ValueError("adopt row without a lesson id")
    role = _text(row.get("role_label"))
    destination = _text(tgt.get("destination")) or _text(row.get("scope")) or "local"
    act = _activity(proj, row)
    note = note_iri(cid, note_id)
    node = copy_iri(cid, role, destination, note_id)
    g.add(node, RDF.type, ACC.PublishedNote)
    g.add(node, PROV.wasDerivedFrom, note)
    g.add(node, PROV.wasGeneratedBy, act)
    g.add(node, ACC.destination, lit(destination))
    _held(proj, node, cid, role, row)
    g.add(act, PROV.used, note)
    _episodes(proj, cid, node, ev.get("source_episode_ids"))


def _forget(proj: Projection, row: dict[str, Any]) -> None:
    g = proj.graph
    cid = _text(row.get("collective_id")) or "local"
    ev = row.get("evidence") or {}
    act = _activity(proj, row, ACC.Erasure)
    for note_id in ev.get("notes_deleted") or []:
        g.add(note_iri(cid, _text(note_id)), PROV.wasInvalidatedBy, act)
    for key in ("notes_demoted", "notes_rebuilt"):
        for note_id in ev.get(key) or []:
            g.add(act, ACC.revised, note_iri(cid, _text(note_id)))


def _rollback(proj: Projection, row: dict[str, Any]) -> None:
    g = proj.graph
    cid = _text(row.get("collective_id")) or "local"
    tgt = row.get("target") or {}
    note_id = _text(tgt.get("id"))
    if not note_id:
        raise ValueError("rollback row without a target")
    act = _activity(proj, row)
    if tgt.get("store") == "memory_notes":
        g.add(note_iri(cid, note_id), PROV.wasInvalidatedBy, act)
    elif tgt.get("store") == "shared_notes" and _text(tgt.get("destination")):
        g.add(copy_iri(cid, _text(row.get("role_label")), _text(tgt["destination"]), note_id),
              PROV.wasInvalidatedBy, act)


def _outcome(proj: Projection, row: dict[str, Any]) -> None:
    g = proj.graph
    cid = _text(row.get("collective_id")) or "local"
    measured, tgt = row.get("measured") or {}, row.get("target") or {}
    task_id, lesson_id = _text(measured.get("task_id")), _text(tgt.get("id"))
    if not task_id or not lesson_id:
        raise ValueError("outcome row without a task or lesson")
    task = local_iri(cid, "task", task_id)
    g.add(task, RDF.type, ACC.Task)
    g.add(task, PROV.used, note_iri(cid, lesson_id))
    if _text(measured.get("verdict")):
        g.add(task, ACC.verdict, lit(_text(measured["verdict"])))


_ROW: dict[str, Callable[[Projection, dict[str, Any]], None]] = {
    "note": _note, "propose": _propose, "publish": _publish, "hub_promote": _publish,
    "adopt": _adopt, "forget": _forget, "rollback": _rollback, "outcome": _outcome,
}


# ---------------------------------------------------------------------------
# traversals
# ---------------------------------------------------------------------------
class Index:
    """``s -> p -> {o}`` and ``p -> o -> {s}`` over a graph.

    Building it is one pass over every triple; a caller asking several
    questions of one graph builds it once and passes it to each traversal
    (the live edge ledger projects to ~95k triples).
    """

    def __init__(self, graph: Graph) -> None:
        self.out: dict[Any, dict[str, set]] = {}
        self.into: dict[str, dict[Any, set]] = {}
        for s, p, o in graph:
            self.out.setdefault(s, {}).setdefault(p, set()).add(o)
            self.into.setdefault(p, {}).setdefault(o, set()).add(s)

    def objects(self, s: Any, p: str) -> set:
        return self.out.get(s, {}).get(p, set())

    def subjects(self, p: str, o: Any) -> set:
        return self.into.get(p, {}).get(o, set())


def _rank(level: str) -> int:
    order = ("LOW", "MEDIUM", "HIGH", "CRITICAL")
    text = str(level or "").upper()
    return order.index(text) if text in order else len(order) - 1


def _visible(idx: Index, node: Any, reader_ceiling: str) -> bool:
    """The information rule on the graph: an entity above the reader's
    ceiling is not shown.  An entity with no ceiling (an episode id, a task)
    carries no content of its own and is shown."""
    ceilings = idx.objects(node, ACC.ceiling)
    if not ceilings:
        return True
    have = _rank(reader_ceiling)
    return all(_rank(str(c).rsplit(":", 1)[-1]) <= have for c in ceilings)


@dataclass
class Lineage:
    """Where one note came from, and everywhere it went."""

    note: str
    upstream: list[str] = field(default_factory=list)      # episodes, in IRI order
    proposals: list[str] = field(default_factory=list)
    copies: list[str] = field(default_factory=list)        # published / adopted copies, transitively
    invalidated_by: list[str] = field(default_factory=list)
    used_by: list[str] = field(default_factory=list)       # tasks
    hidden: int = 0                                        # entities above the reader's ceiling
    note_visible: bool = True                              # False: the note itself is above it


def find_notes(graph: Graph, prefix: str) -> list[str]:
    """Note IRIs whose id starts with *prefix* (any collective)."""
    out = set()
    for s, p, o in graph:
        if p == RDF.type and o == ACC.Note and str(s).rsplit(":", 1)[-1].startswith(prefix):
            out.add(str(s))
    return sorted(out)


def lineage(graph: Graph, note: str, *, reader_ceiling: str = "CRITICAL",
            index: Index | None = None) -> Lineage:
    idx = index or Index(graph)
    out = Lineage(note=note)
    if not _visible(idx, note, reader_ceiling):
        out.hidden, out.note_visible = 1, False
        return out
    out.upstream = sorted(str(e) for e in idx.objects(note, PROV.wasDerivedFrom))
    for act in idx.subjects(PROV.used, note):
        for proposal in idx.subjects(PROV.wasGeneratedBy, act):
            if ACC.Proposal in idx.objects(proposal, RDF.type):
                if _visible(idx, proposal, reader_ceiling):
                    out.proposals.append(str(proposal))
                else:
                    out.hidden += 1
    out.proposals.sort()
    seen, queue = {note}, deque([note])
    while queue:
        current = queue.popleft()
        for derived in idx.subjects(PROV.wasDerivedFrom, current):
            if derived in seen or ACC.PublishedNote not in idx.objects(derived, RDF.type):
                continue
            seen.add(derived)
            if _visible(idx, derived, reader_ceiling):
                out.copies.append(str(derived))
            else:
                out.hidden += 1
            queue.append(derived)
    out.copies.sort()
    out.invalidated_by = sorted(str(a) for a in idx.objects(note, PROV.wasInvalidatedBy))
    out.used_by = sorted(str(t) for t in idx.subjects(PROV.used, note)
                         if ACC.Task in idx.objects(t, RDF.type))
    return out


def approvals_of(graph: Graph, copy: str, *, index: Index | None = None) -> list[tuple[Any, str]]:
    """``[(person node, tier)]`` for the activity that generated *copy*."""
    idx = index or Index(graph)
    out = []
    for act in idx.objects(copy, PROV.wasGeneratedBy):
        for assoc in idx.objects(act, PROV.qualifiedAssociation):
            tiers = idx.objects(assoc, ACC.approverTier)
            for person in idx.objects(assoc, PROV.agent):
                out.append((person, str(next(iter(tiers)).value) if tiers else ""))
    return sorted(out, key=lambda t: str(t[0]))


@dataclass
class Contributions:
    """Everything resting on one person: the erasure plan, before anything is deleted."""

    person: str
    notes: list[str] = field(default_factory=list)       # notes the person is a source of
    copies: list[str] = field(default_factory=list)      # copies derived from them, transitively
    already_erased: list[str] = field(default_factory=list)


def contributions(proj: Projection, subject: str) -> Contributions:
    """The ``prov:wasDerivedFrom*`` closure from every note naming *subject*.

    Not ceiling-filtered: an erasure plan has to see everything it will touch,
    and only an operator may run one.
    """
    idx = Index(proj.graph)
    person = proj.person(subject)
    out = Contributions(person=proj.person_of(subject))
    roots = sorted((str(n) for n in idx.subjects(ACC.sourceRequester, person)
                    if ACC.Note in idx.objects(n, RDF.type)))
    seen, queue = set(roots), deque(roots)
    while queue:
        current = queue.popleft()
        for derived in idx.subjects(PROV.wasDerivedFrom, current):
            if derived not in seen and ACC.PublishedNote in idx.objects(derived, RDF.type):
                seen.add(derived)
                out.copies.append(str(derived))
                queue.append(derived)
    for note in roots:
        (out.already_erased if idx.objects(note, PROV.wasInvalidatedBy) else out.notes).append(note)
    out.copies.sort()
    return out


def unexplained(graph: Graph) -> list[str]:
    """Notes something derives from or uses that no ``note`` row generated.

    The projection's consistency check: each one is a gap in the ledger --
    a row older than the 30-day Redis mirror read without the file, or a
    note the ledger never saw.
    """
    idx = Index(graph)
    referenced = set()
    for p in (PROV.wasDerivedFrom, PROV.used):
        for o in idx.into.get(p, {}):
            if isinstance(o, str) and ":note:" in o:
                referenced.add(o)
    return sorted(o for o in referenced if not idx.objects(o, PROV.wasGeneratedBy))


