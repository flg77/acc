"""A promptfoo configuration from ACC's golden prompts (058 Phase 4, step 19).

The golden prompts already say what a good answer contains
(``expects.output_contains`` / ``output_matches_regex``).  promptfoo runs the
same prompts against ACC's OpenAI-compatible endpoint, where ``model`` names
the role, and asserts the same things.  That gives an edge profile a standard
eval report and puts it in MLflow, without a second set of expectations to
keep in step.

Pure: builds the dict; the CLI writes it and the container runs it.
"""

from __future__ import annotations

from typing import Any, Iterable

#: The promptfoo release the container pins (deploy/evals/podman-compose.evals.yml).
PROMPTFOO_IMAGE = "ghcr.io/promptfoo/promptfoo:0.118.0"


def build_config(
    prompts: Iterable[Any],
    *,
    base_url: str,
    api_key_env: str = "ACC_COMPAT_API_KEY",
    name_prefix: str = "",
) -> dict:
    """promptfoo's ``promptfooconfig.yaml`` as a dict: one provider per role
    the prompts target, one test per golden prompt."""
    prompts = [p for p in prompts if not name_prefix or p.name.startswith(name_prefix)]
    roles = sorted({p.target_role for p in prompts})
    providers = [
        {
            "id": f"openai:chat:{role}",
            "label": role,
            "config": {"apiBaseUrl": base_url.rstrip("/"), "apiKeyEnvar": api_key_env},
        }
        for role in roles
    ]
    tests = []
    for p in prompts:
        asserts: list[dict] = [{"type": "icontains", "value": s} for s in p.expects.output_contains]
        if p.expects.output_matches_regex:
            asserts.append({"type": "regex", "value": p.expects.output_matches_regex})
        if p.expects.reply_non_empty:
            asserts.append({"type": "javascript", "value": "output.trim().length > 0"})
        tests.append({
            "description": p.name,
            "vars": {"prompt": p.prompt},
            "providers": [p.target_role],
            "assert": asserts,
            "metadata": {"acc_golden": p.name, "role": p.target_role},
        })
    return {
        "description": "ACC golden prompts (generated by acc-cli evals promptfoo-config)",
        "prompts": ["{{prompt}}"],
        "providers": providers,
        "tests": tests,
        "outputPath": "/out/promptfoo-results.json",
    }
